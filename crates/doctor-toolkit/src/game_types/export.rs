//! The typed game data in the forms other tools read: JSON Schema (MCP
//! clients, `mod.json`) and a Python module with its stub.
//!
//! The files are generated (`doctor-toolkit types-gen`) and kept in the
//! repository; a test checks that they are up to date.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde_json::{Value as Json, json};

use super::{EnumDef, EnumKind, enums, message};
use crate::Result;

/// Path of the JSON Schema below the repository root.
pub const SCHEMA_PATH: &str = "data/gf2/schema/gf2-types.schema.json";
/// Path of the Python module below the repository root.
pub const PYTHON_MODULE_PATH: &str = "crates/doctor-toolkit-py/python/doctor_toolkit/gf2_types.py";
/// Path of the Python stub below the repository root.
pub const PYTHON_STUB_PATH: &str = "crates/doctor-toolkit-py/python/doctor_toolkit/gf2_types.pyi";

const GENERATED: &str = "Generated by `doctor-toolkit types-gen` from data/gf2/ (enums.toml, engine_messages.txt); do not edit.";

fn enum_schema(e: &EnumDef) -> Json {
    let description = format!("{}. Source: {} ({}).", e.title, e.source, conf_name(e));
    let notes: serde_json::Map<String, Json> = e
        .values
        .iter()
        .filter(|v| !v.note.is_empty())
        .map(|v| (v.label(), Json::from(v.note)))
        .collect();
    let mut schema = match e.kind {
        EnumKind::Hash | EnumKind::Name | EnumKind::Bits => json!({
            "type": "string",
            "enum": e.values.iter().filter_map(|v| v.name).collect::<Vec<_>>(),
        }),
        EnumKind::Int => json!({
            "type": "integer",
            "enum": e.values.iter().filter_map(|v| v.value).collect::<Vec<_>>(),
        }),
    };
    let o = schema.as_object_mut().expect("object");
    o.insert("title".into(), e.title.into());
    o.insert("description".into(), description.into());
    o.insert("x-stored-as".into(), e.kind.name().into());
    if e.kind == EnumKind::Hash {
        let hashes: serde_json::Map<String, Json> = e
            .values
            .iter()
            .filter_map(|v| Some((v.name?.to_owned(), format!("{:08x}", v.hash?).into())))
            .collect();
        o.insert("x-hashes".into(), hashes.into());
    }
    if e.kind == EnumKind::Bits
        || e.values
            .iter()
            .any(|v| v.name.is_some() && v.value.is_some())
    {
        let numbers: serde_json::Map<String, Json> = e
            .values
            .iter()
            .filter_map(|v| Some((v.name?.to_owned(), v.value?.into())))
            .collect();
        o.insert("x-values".into(), numbers.into());
    }
    if !notes.is_empty() {
        o.insert("x-notes".into(), notes.into());
    }
    schema
}

fn conf_name(e: &EnumDef) -> &'static str {
    match e.conf {
        super::Confidence::Exe => "exe",
        super::Confidence::Data => "data",
        super::Confidence::Guess => "guess",
    }
}

/// JSON Schema (draft 2020-12) with a definition for every value list and
/// for message names. Tools refer to `#/$defs/<list>`.
pub fn json_schema() -> Json {
    let mut defs = serde_json::Map::new();
    for e in enums() {
        defs.insert(e.key.to_owned(), enum_schema(e));
    }
    let mut engine: Vec<&str> = message::engine_messages().iter().map(|e| e.1).collect();
    engine.sort_by_key(|n| n.to_ascii_lowercase());
    defs.insert(
        "engine_message".into(),
        json!({
            "title": "Messages named by godfather2.exe",
            "description": "Source: data/gf2/engine_messages.txt (exe). Letter case does not matter: the game hashes the lower-case name.",
            "type": "string",
            "enum": engine,
        }),
    );
    defs.insert(
        "message_name".into(),
        json!({
            "title": "Message name",
            "description": "A message of the bus: an engine message, a message of the game files (data/gf2/game_messages.tsv) or a new one. On the bus it is sdbm(lower(name)).",
            "type": "string",
            "minLength": 1,
            "pattern": "^[\\x20-\\x7E]+$",
        }),
    );
    defs.insert(
        "mod_messages".into(),
        json!({
            "title": "Messages a mod adds",
            "description": "`messages` of mod.json: names the SimGroups of the mod send or hear and the game does not have. A name must not be a game message and its hash must not be the hash of one (`mods build` and `validate` check).",
            "type": "array",
            "items": { "$ref": "#/$defs/message_name" },
            "uniqueItems": true,
        }),
    );
    defs.insert(
        "message".into(),
        json!({
            "title": "Message as tools report it",
            "type": "object",
            "required": ["kind", "hash"],
            "properties": {
                "kind": { "enum": ["engine", "game", "custom", "unknown"] },
                "name": { "type": ["string", "null"] },
                "hash": { "type": "integer", "minimum": 0, "maximum": 4294967295u32 },
                "owner": { "type": ["string", "null"], "description": "The mod of a custom message." },
                "usage": { "enum": [
                    "sent_and_heard", "heard_from_engine", "sent_to_engine",
                    "heard_never_sent", "sent_never_heard", "engine_only", "not_in_game"
                ] },
                "data": { "type": "string", "description": "The data word; \"unknown\" unless read in the code." },
                "conf": { "enum": ["exe", "data", "bench", "guess", null] },
            },
        }),
    );
    let lists = enums().iter().map(|e| e.key).collect::<Vec<_>>().join("|");
    defs.insert(
        "semantic_type".into(),
        json!({
            "title": "Meaning of a SimGroup attribute",
            "description": "Source: data/gf2/attr_types.toml and the pins of data/gf2/logic_schema.toml.",
            "type": "string",
            "pattern": format!("^(MsgIn|MsgOut|Seconds|Money|Bool|Ref<[A-Za-z0-9_]+>|Res<[a-z0-9]+>|Enum<({lists})>)$"),
        }),
    );
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/Darkildo/doctor_toolkit/blob/main/data/gf2/schema/gf2-types.schema.json",
        "title": "Typed game data of The Godfather II (PC 1.0.789.0)",
        "$comment": GENERATED,
        "$defs": defs,
    })
}

/// Pretty JSON with the keys of every object sorted: the text does not
/// depend on how `serde_json` keeps maps (its `preserve_order` feature may be
/// turned on by another crate of the build).
fn write_sorted(value: &Json, indent: usize, out: &mut String) {
    let pad = |n: usize, out: &mut String| out.push_str(&"  ".repeat(n));
    match value {
        Json::Object(map) if !map.is_empty() => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push_str("{\n");
            for (i, key) in keys.iter().enumerate() {
                pad(indent + 1, out);
                out.push_str(&serde_json::to_string(key).expect("a string"));
                out.push_str(": ");
                write_sorted(&map[*key], indent + 1, out);
                out.push_str(if i + 1 < keys.len() { ",\n" } else { "\n" });
            }
            pad(indent, out);
            out.push('}');
        }
        Json::Array(items) if !items.is_empty() => {
            out.push_str("[\n");
            for (i, item) in items.iter().enumerate() {
                pad(indent + 1, out);
                write_sorted(item, indent + 1, out);
                out.push_str(if i + 1 < items.len() { ",\n" } else { "\n" });
            }
            pad(indent, out);
            out.push(']');
        }
        other => out.push_str(&other.to_string()),
    }
}

/// The JSON Schema as the text of the file.
pub fn json_schema_text() -> String {
    let mut text = String::new();
    write_sorted(&json_schema(), 0, &mut text);
    text.push('\n');
    text
}

/// `rosato_carmine` → `ROSATO_CARMINE`; names that are not identifiers get none.
fn python_constant(name: &str) -> String {
    name.chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn python_type(key: &str) -> String {
    key.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn python_literal(e: &EnumDef, v: &super::EnumValue) -> String {
    match (e.kind, v.name, v.value) {
        (EnumKind::Int, _, Some(n)) => n.to_string(),
        (_, Some(name), _) => format!("{name:?}"),
        (_, None, Some(n)) => n.to_string(),
        (_, None, None) => "None".to_owned(),
    }
}

/// The Python stub: a `Literal` type and the tuple of values for every list,
/// and the engine messages.
pub fn python_stub() -> String {
    let mut out = format!(
        "\"\"\"Typed game data of The Godfather II (PC 1.0.789.0).\n\n{GENERATED}\n\"\"\"\n\n"
    );
    out.push_str("from typing import Final, Literal, Optional, TypedDict\n\n");
    out.push_str("class EnumValue(TypedDict):\n    name: Optional[str]\n    value: Optional[int]\n    hash: Optional[int]\n    note: str\n\n");
    out.push_str("class EnumInfo(TypedDict):\n    title: str\n    kind: Literal[\"hash\", \"name\", \"int\", \"bits\"]\n    source: str\n    conf: Literal[\"exe\", \"data\", \"guess\"]\n    values: tuple[EnumValue, ...]\n\n");
    for e in enums() {
        let ty = python_type(e.key);
        let literals: Vec<String> = e.values.iter().map(|v| python_literal(e, v)).collect();
        writeln!(out, "{ty} = Literal[\n    {},\n]", literals.join(",\n    ")).unwrap();
        writeln!(
            out,
            "{}: Final[tuple[{ty}, ...]]\n\"\"\"{} ({}; stored as {}).\"\"\"\n",
            python_constant(e.key),
            e.title,
            conf_name(e),
            e.kind.name()
        )
        .unwrap();
    }
    let mut engine: Vec<&str> = message::engine_messages().iter().map(|e| e.1).collect();
    engine.sort_by_key(|n| n.to_ascii_lowercase());
    let literals: Vec<String> = engine.iter().map(|n| format!("{n:?}")).collect();
    writeln!(
        out,
        "EngineMessage = Literal[\n    {},\n]",
        literals.join(",\n    ")
    )
    .unwrap();
    out.push_str("ENGINE_MESSAGES: Final[tuple[EngineMessage, ...]]\n\"\"\"Messages named by godfather2.exe.\"\"\"\n\n");
    out.push_str("ENUMS: Final[dict[str, EnumInfo]]\n\"\"\"Every value list by key, with sources and notes.\"\"\"\n\n");
    out.push_str("def message_hash(name: str) -> int:\n    \"\"\"`sdbm(lower(name))`: the message as the game's bus has it.\"\"\"\n\n");
    out.push_str("def enum_hash(name: str) -> int:\n    \"\"\"What a hash attribute stores for a name of a list (the same hash).\"\"\"\n");
    out
}

fn python_string(text: &str) -> String {
    serde_json::to_string(text).expect("a string")
}

/// The Python module with the values the stub declares.
pub fn python_module() -> String {
    let mut out = format!(
        "\"\"\"Typed game data of The Godfather II (PC 1.0.789.0).\n\n{GENERATED}\n\"\"\"\n\n"
    );
    for e in enums() {
        let literals: Vec<String> = e.values.iter().map(|v| python_literal(e, v)).collect();
        writeln!(
            out,
            "{} = (\n    {},\n)\n",
            python_constant(e.key),
            literals.join(",\n    ")
        )
        .unwrap();
    }
    let mut engine: Vec<&str> = message::engine_messages().iter().map(|e| e.1).collect();
    engine.sort_by_key(|n| n.to_ascii_lowercase());
    let literals: Vec<String> = engine.iter().map(|n| format!("{n:?}")).collect();
    writeln!(
        out,
        "ENGINE_MESSAGES = (\n    {},\n)\n",
        literals.join(",\n    ")
    )
    .unwrap();
    out.push_str("ENUMS = {\n");
    for e in enums() {
        writeln!(
            out,
            "    {:?}: {{\n        \"title\": {},\n        \"kind\": {:?},\n        \"source\": {},\n        \"conf\": {:?},\n        \"values\": (",
            e.key,
            python_string(e.title),
            e.kind.name(),
            python_string(e.source),
            conf_name(e)
        )
        .unwrap();
        for v in e.values {
            let opt = |x: Option<String>| x.unwrap_or_else(|| "None".to_owned());
            writeln!(
                out,
                "            {{\"name\": {}, \"value\": {}, \"hash\": {}, \"note\": {}}},",
                opt(v.name.map(python_string)),
                opt(v.value.map(|n| n.to_string())),
                opt(v.hash.map(|h| format!("0x{h:08x}"))),
                python_string(v.note)
            )
            .unwrap();
        }
        out.push_str("        ),\n    },\n");
    }
    out.push_str("}\n\n\n");
    out.push_str("def message_hash(name):\n    \"\"\"`sdbm(lower(name))`: the message as the game's bus has it.\"\"\"\n    h = 0\n    for c in name.encode(\"latin-1\"):\n        if 0x41 <= c <= 0x5A:\n            c += 0x20\n        h = (c + h * 65599) & 0xFFFFFFFF\n    return h\n\n\n");
    out.push_str("def enum_hash(name):\n    \"\"\"What a hash attribute stores for a name of a list (the same hash).\"\"\"\n    return message_hash(name)\n");
    out
}

/// The generated files: path below the repository root and text.
pub fn files() -> Vec<(&'static str, String)> {
    vec![
        (SCHEMA_PATH, json_schema_text()),
        (PYTHON_MODULE_PATH, python_module()),
        (PYTHON_STUB_PATH, python_stub()),
    ]
}

/// Writes the generated files below `root`, or with `check` only compares.
/// Returns the files that differ (after writing them, without `check`).
pub fn write(root: &Path, check: bool) -> Result<Vec<PathBuf>> {
    let mut changed = Vec::new();
    for (rel, text) in files() {
        let path = root.join(rel);
        if std::fs::read_to_string(&path).is_ok_and(|old| old == text) {
            continue;
        }
        if !check {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir).map_err(|e| crate::Error::io(dir, e))?;
            }
            std::fs::write(&path, &text).map_err(|e| crate::Error::io(&path, e))?;
        }
        changed.push(path);
    }
    Ok(changed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_schema_defines_every_list() {
        let schema = json_schema();
        let defs = schema["$defs"].as_object().unwrap();
        for e in enums() {
            assert!(defs.contains_key(e.key), "{}", e.key);
        }
        assert_eq!(defs["family"]["enum"].as_array().unwrap().len(), 28);
        assert_eq!(defs["family"]["x-hashes"]["corleone"], "0637b907");
        assert_eq!(defs["venue"]["type"], "integer");
        assert_eq!(defs["crew_specialty"]["x-values"]["medic"], 64);
        assert!(defs["engine_message"]["enum"].as_array().unwrap().len() > 500);
        assert!(defs.contains_key("mod_messages"));
    }

    #[test]
    fn python_files_declare_the_same_names() {
        let stub = python_stub();
        let module = python_module();
        for e in enums() {
            let constant = python_constant(e.key);
            assert!(stub.contains(&format!("{constant}: Final")), "{constant}");
            assert!(module.contains(&format!("{constant} = (")), "{constant}");
        }
        assert!(stub.contains("Family = Literal["));
        assert!(module.contains("\"corleone\""));
        assert!(module.contains("def message_hash(name):"));
    }
}

//! The table of named addresses of `godfather2.exe` (stage 99): made from
//! the address tables of the notes in `docs/kb/exe/`, written to
//! `data/gf2/exe_symbols.tsv`. The crash handler of the game
//! (`doctor_crash.asi`) and `crash-report` name the place of a crash by it,
//! so the knowledge base stays the one source: a new row in a note becomes
//! a name in the next report after `doctor-toolkit kb-gen`.
//!
//! A row of a note is `| address(es) | what it is | source |`; every
//! address of the first cell (`0x` and eight hexadecimal digits in
//! backticks) gets a line `ADDRESS<TAB>note<TAB>what`.

use std::path::Path;

use super::{Kb, io_error};
use crate::Result;

/// The generated table, from the repository root.
pub const SYMBOLS_FILE: &str = "data/gf2/exe_symbols.tsv";

/// The longest description kept, in characters.
const MAX_WHAT: usize = 200;

const HEADER: &str = "\
# Named addresses of godfather2.exe (PC 1.0.789.0): what the knowledge base
# says about each address of the tables in docs/kb/exe/*.md. Generated by
# `doctor-toolkit kb-gen`; do not edit by hand — edit the note and run it.
# Columns (tab-separated): address (hexadecimal), note (file in docs/kb/exe
# without .md), what it is. Sorted by address, then by note.
";

/// The cells of a table row: split at `|` outside inline code, `\|` kept.
fn cells(line: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cell = String::new();
    let mut code = false;
    let mut chars = line.trim().chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '`' => {
                code = !code;
                cell.push(c);
            }
            '\\' if chars.peek() == Some(&'|') => {
                cell.push('|');
                chars.next();
            }
            '|' if !code => {
                out.push(cell.trim().to_owned());
                cell.clear();
            }
            _ => cell.push(c),
        }
    }
    if !cell.trim().is_empty() {
        out.push(cell.trim().to_owned());
    }
    // The row starts with `|`: the first cell is empty.
    if out.first().is_some_and(String::is_empty) {
        out.remove(0);
    }
    out
}

/// The addresses of a first cell: `` `0x00408A00` `` and the like.
fn addresses(cell: &str) -> Vec<u32> {
    let mut out = Vec::new();
    for part in cell.split('`').skip(1).step_by(2) {
        let Some(hex) = part.strip_prefix("0x").or_else(|| part.strip_prefix("0X")) else {
            continue;
        };
        if hex.len() == 8
            && let Ok(a) = u32::from_str_radix(hex, 16)
        {
            out.push(a);
        }
    }
    out
}

/// A description on one line, without tabs, cut to [`MAX_WHAT`].
fn what(cell: &str) -> String {
    let flat: Vec<&str> = cell.split_whitespace().collect();
    let flat = flat.join(" ");
    if flat.chars().count() <= MAX_WHAT {
        return flat;
    }
    let mut cut: String = flat.chars().take(MAX_WHAT - 1).collect();
    cut.push('…');
    cut
}

/// The text of the table for the notes of `kb` (paths `exe/<note>.md`).
pub fn render(kb: &Kb) -> String {
    let mut rows: Vec<(u32, String, String)> = Vec::new();
    for note in &kb.notes {
        let Some(stem) = note
            .rel
            .strip_prefix("exe/")
            .and_then(|n| n.strip_suffix(".md"))
        else {
            continue;
        };
        if stem == "index" {
            continue;
        }
        for line in note.body().lines() {
            if !line.trim_start().starts_with("| `0") {
                continue;
            }
            let cells = cells(line);
            let (Some(first), Some(second)) = (cells.first(), cells.get(1)) else {
                continue;
            };
            let text = what(second);
            for address in addresses(first) {
                rows.push((address, stem.to_owned(), text.clone()));
            }
        }
    }
    rows.sort();
    rows.dedup();
    let mut out = String::from(HEADER);
    for (address, note, text) in rows {
        out.push_str(&format!("{address:08X}\t{note}\t{text}\n"));
    }
    out
}

/// Writes the table of the repository in `root` from its knowledge base in
/// `kb_dir`. Returns whether the file was (or, with `check`, would be)
/// changed.
pub fn run(root: &Path, kb_dir: &Path, check: bool) -> Result<bool> {
    let text = render(&Kb::load(kb_dir)?);
    let path = root.join(SYMBOLS_FILE);
    let existing = std::fs::read_to_string(&path)
        .map(|t| t.replace("\r\n", "\n"))
        .unwrap_or_default();
    if existing == text {
        return Ok(false);
    }
    if !check {
        std::fs::write(&path, text).map_err(|e| io_error(&path, e))?;
    }
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_of_a_note_become_lines() {
        let note = "---\ntype: exe\n---\n# Bus\n\n| Адрес | Что это | Источник |\n|---|---|---|\n\
| `0x00408A00` | отправка `bool Send(a \\| b)`,   `cdecl` | live-link.md §5 |\n\
| `0x00407E60`, `0x004084D0` | подписка | logic-graph.md §1 |\n\
| `0x6E756F7B` | падение (адрес вне образа) | queens.md §7 |\n\
| [not an address](x.md) | known | exe |\n";
        let kb = Kb::from_texts([("exe/bus.md", note), ("engine/other.md", note)]);
        let text = render(&kb);
        let lines: Vec<&str> = text.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            lines,
            [
                "00407E60\tbus\tподписка",
                "004084D0\tbus\tподписка",
                "00408A00\tbus\tотправка `bool Send(a | b)`, `cdecl`",
                "6E756F7B\tbus\tпадение (адрес вне образа)",
            ]
        );
    }

    #[test]
    fn a_long_description_is_cut() {
        let long = "я".repeat(300);
        let cut = what(&long);
        assert_eq!(cut.chars().count(), MAX_WHAT);
        assert!(cut.ends_with('…'));
    }
}

#[derive(Debug, Default)]
struct AttrRow {
    kind: Option<String>,
    /// Non-default values seen in the game files.
    count: Option<u32>,
    /// Name a metamodel of the game gives the attribute.
    data_name: Option<String>,
    pin: Option<AttrPin>,
}

#[derive(Debug, Default)]
struct ClassInfo {
    name: Option<String>,
    category: Option<schema::Category>,
    layout: Option<Vec<(u32, u16)>>,
    attrs: BTreeMap<u16, AttrRow>,
    /// Object classes whose new object has a packet of this class.
    used_in: Vec<u32>,
    in_schema: bool,
    in_logic: bool,
}

fn class_stem(hash: u32, info: &ClassInfo) -> String {
    info.name
        .clone()
        .unwrap_or_else(|| format!("class-{hash:08x}"))
}

fn class_label(hash: u32, info: &ClassInfo) -> String {
    info.name.clone().unwrap_or_else(|| format!("0x{hash:08x}"))
}

fn is_hash_name(name: &str) -> bool {
    name.len() == 8 && name.chars().all(|c| c.is_ascii_hexdigit())
}

fn classes(inputs: &Inputs, logic: &LogicSchema) -> Result<BTreeMap<u32, ClassInfo>> {
    let mut out: BTreeMap<u32, ClassInfo> = BTreeMap::new();
    for name in list_lines(inputs.sim_classes) {
        let hash = sdbm(name.to_ascii_lowercase().as_bytes());
        out.entry(hash).or_default().name = Some(name.to_owned());
    }
    for line in list_lines(inputs.simgroup_schema) {
        let mut cols = line.split_whitespace();
        let (Some(class), Some(index), Some(kind)) = (cols.next(), cols.next(), cols.next()) else {
            return Err(bad(format!("simgroup schema: short line `{line}`")));
        };
        let class = u32::from_str_radix(class, 16)
            .map_err(|_| bad(format!("simgroup schema: bad class in `{line}`")))?;
        let index: u16 = index
            .parse()
            .map_err(|_| bad(format!("simgroup schema: bad index in `{line}`")))?;
        let info = out.entry(class).or_default();
        info.in_schema = true;
        let row = info.attrs.entry(index).or_default();
        row.kind = Some(kind.to_owned());
        row.count = cols.next().and_then(|c| c.parse().ok());
        row.data_name = cols.next().map(str::to_owned);
    }
    for class in logic.packet_classes() {
        let info = out.entry(class).or_default();
        info.in_logic = true;
        for pin in logic.packet(class) {
            info.attrs.entry(pin.index).or_default().pin = Some(pin.clone());
        }
    }
    for (class, _, category) in logic.classes() {
        let info = out.entry(class).or_default();
        info.in_logic = true;
        info.category = Some(category);
        if let Some(layout) = logic.layout(class) {
            info.layout = Some(layout.to_vec());
        }
    }
    let layouts: Vec<(u32, Vec<u32>)> = out
        .iter()
        .filter_map(|(&class, info)| {
            let layout = info.layout.as_ref()?;
            Some((class, layout.iter().map(|&(c, _)| c).collect()))
        })
        .collect();
    for (class, packets) in layouts {
        for packet in packets {
            let info = out.entry(packet).or_default();
            if packet != class && !info.used_in.contains(&class) {
                info.used_in.push(class);
            }
        }
    }
    for (&class, info) in &mut out {
        if info.name.is_none()
            && let Some(name) = logic.class_name(class)
            && !is_hash_name(name)
        {
            info.name = Some(name.to_owned());
        }
    }
    let mut stems = HashSet::new();
    for (&class, info) in &out {
        let stem = class_stem(class, info).to_lowercase();
        if !stems.insert(stem.clone()) {
            return Err(bad(format!("two classes would share the note `{stem}.md`")));
        }
    }
    Ok(out)
}

fn pin_role(pin: &AttrPin) -> String {
    match pin.pin {
        PinKind::In => "вход (сообщение, которое объект слушает)".to_owned(),
        PinKind::Out => match pin.delay {
            Some(delay) => {
                format!("выход (сообщение, которое объект шлёт; задержка — атрибут {delay})")
            }
            None => "выход (сообщение, которое объект шлёт)".to_owned(),
        },
        PinKind::Link => "ссылка на объект (GUID)".to_owned(),
        PinKind::Asset => "ссылка на ресурс".to_owned(),
        PinKind::Param => "параметр".to_owned(),
    }
}

fn conf_name(conf: schema::Confidence) -> &'static str {
    match conf {
        schema::Confidence::Exe => "exe",
        schema::Confidence::Data => "data",
        schema::Confidence::Guess => "guess",
    }
}

/// The meaning of an attribute as a table cell, with a link to the class
/// or the list it names.
fn semantic_cell(ty: SemanticType, all: &BTreeMap<u32, ClassInfo>) -> String {
    match ty {
        SemanticType::Ref(class) => {
            let hash = game_types::class_hash(class);
            match all.get(&hash) {
                Some(info) => format!("[`Ref<{class}>`]({}.md)", class_stem(hash, info)),
                None => format!("`Ref<{class}>`"),
            }
        }
        SemanticType::Resource(tag) => format!("[`Res<{tag}>`](../resources/{tag}.md)"),
        SemanticType::Enum(key) => format!("[`Enum<{key}>`](../enums/{key}.md)"),
        other => format!("`{other}`"),
    }
}

fn class_note(
    hash: u32,
    info: &ClassInfo,
    all: &BTreeMap<u32, ClassInfo>,
    tunables: &[Tunable],
) -> Draft {
    let link = |class: u32| {
        let other = &all[&class];
        format!(
            "[{}]({}.md)",
            class_label(class, other),
            class_stem(class, other)
        )
    };
    let title = match &info.name {
        Some(name) => format!("Класс `{name}`"),
        None => format!("Класс `0x{hash:08x}` (имя неизвестно)"),
    };
    let mut draft = Draft::new(
        format!("classes/{}.md", class_stem(hash, info)),
        NoteType::Class,
        title,
    );
    let mut b = String::new();
    match &info.name {
        Some(name) => {
            let _ = writeln!(
                b,
                "- Хэш класса: `0x{hash:08x}` — SDBM имени `{name}` в нижнем регистре."
            );
        }
        None => {
            let _ = writeln!(
                b,
                "- Хэш класса: `0x{hash:08x}`; имя не восстановлено (хэш — SDBM имени в нижнем регистре)."
            );
        }
    }
    match info.category {
        Some(category) => {
            let _ = writeln!(
                b,
                "- Класс объектов; категория в графе логики: `{}`.",
                category.name()
            );
        }
        None => b.push_str(
            "- Объектов этого класса в схеме графа логики нет: это пакет атрибутов базового \
             класса или компонента.\n",
        ),
    }
    if let Some(layout) = &info.layout {
        let packets: Vec<String> = layout
            .iter()
            .map(|&(class, count)| format!("{} ({count})", link(class)))
            .collect();
        let _ = writeln!(
            b,
            "- Пакеты нового объекта, базовый класс первым (в скобках — число атрибутов): {}.",
            packets.join(", ")
        );
    }
    if !info.used_in.is_empty() {
        const SHOWN: usize = 12;
        let mut users: Vec<(String, u32)> = info
            .used_in
            .iter()
            .map(|&c| (class_label(c, &all[&c]).to_lowercase(), c))
            .collect();
        users.sort();
        let mut links: Vec<String> = users.iter().take(SHOWN).map(|&(_, c)| link(c)).collect();
        if users.len() > SHOWN {
            links.push(format!("и ещё {}", users.len() - SHOWN));
        }
        let _ = writeln!(
            b,
            "- Пакет этого класса есть у объектов классов ({}): {}.",
            users.len(),
            links.join(", ")
        );
    }
    b.push_str("- Поведение класса (обработчики сообщений, обновление) здесь не описано: см. ручной раздел и карту [логики](../maps/logic.md).\n");

    b.push_str("\n## Атрибуты\n\n");
    if info.attrs.is_empty() {
        b.push_str("В схемах нет ни одного атрибута этого класса.\n");
    } else {
        b.push_str(
            "Вид значения выведен из файлов игры, роль и имя — из схемы графа логики; \
             «значений» — сколько раз атрибут встречен в файлах игры со значением не по \
             умолчанию. «Смысл» — что значит значение, где это известно \
             (`data/gf2/attr_types.toml`): сообщение, ссылка на объект класса, ресурс типа, \
             значение [перечисления](../enums/index.md), секунды, деньги, флаг. Уверенность: \
             `exe` — по коду читателя, `data` — по файлам игры, `guess` — догадка.\n\n",
        );
        b.push_str(
            "| № | Вид | Роль | Имя | Смысл | Уверенность | Значений |\n|---:|---|---|---|---|---|---:|\n",
        );
        for (index, row) in &info.attrs {
            let kind = row
                .kind
                .clone()
                .or_else(|| {
                    row.pin
                        .as_ref()
                        .and_then(|p| p.kind)
                        .map(|k| format!("{k:?}").to_lowercase())
                })
                .unwrap_or_else(|| "—".to_owned());
            let role = row.pin.as_ref().map_or_else(|| "—".to_owned(), pin_role);
            let (name, name_conf) = match (&row.pin, &row.data_name) {
                (
                    Some(AttrPin {
                        name: Some(n),
                        name_conf,
                        ..
                    }),
                    _,
                ) => (format!("`{}`", cell(n)), name_conf.map(conf_name)),
                (_, Some(n)) => (format!("`{}`", cell(n)), Some("data")),
                _ => ("—".to_owned(), None),
            };
            let mut conf = Vec::new();
            if let Some(c) = row.pin.as_ref().and_then(|p| p.conf) {
                conf.push(format!("роль: {}", conf_name(c)));
            }
            if let Some(c) = name_conf {
                conf.push(format!("имя: {c}"));
            }
            let meaning = match row.pin.as_ref().map(|p| p.pin) {
                Some(PinKind::In) => "`MsgIn`".to_owned(),
                Some(PinKind::Out) => "`MsgOut`".to_owned(),
                _ => match game_types::attr_type(hash, *index) {
                    Some(t) => {
                        conf.push(format!("смысл: {}", conf_name(t.conf)));
                        semantic_cell(t.ty, all)
                    }
                    None => "—".to_owned(),
                },
            };
            let conf = if conf.is_empty() {
                "—".to_owned()
            } else {
                conf.join(", ")
            };
            let count = row.count.map_or_else(|| "—".to_owned(), |c| c.to_string());
            let _ = writeln!(
                b,
                "| {index} | {kind} | {role} | {name} | {meaning} | {conf} | {count} |"
            );
        }
    }

    let mine: Vec<&Tunable> = tunables.iter().filter(|t| t.class == hash).collect();
    if !mine.is_empty() {
        b.push_str(
            "\n## Параметры игры\n\nАтрибуты этого класса в списке параметров мастера \
             «Изменить параметры игры» (`data/gf2/tunables.toml`):\n\n",
        );
        b.push_str("| Параметр | Атрибут | Вид | Подпись |\n|---|---:|---|---|\n");
        for t in mine {
            let kind = match t.kind {
                tunables::ValueKind::Int => "int",
                tunables::ValueKind::Float => "float",
                tunables::ValueKind::Bool => "bool",
            };
            let _ = writeln!(
                b,
                "| `{}` | {} | {kind} | {} |",
                t.id,
                t.attribute,
                cell(&t.label)
            );
        }
        draft.meta.sources.push("data/gf2/tunables.toml".to_owned());
    }

    b.push_str(
        "\n## Подробнее\n\n- [Список классов](index.md)\n\
         - [Формат SimGroup](../../formats/simgroup.md)\n\
         - [Граф логики](../../logic-graph.md) §2 — схема пинов\n",
    );
    draft.body = b;

    let exe = info
        .attrs
        .values()
        .filter_map(|r| r.pin.as_ref())
        .any(|p| p.conf == Some(schema::Confidence::Exe));
    draft.meta.status = Status::Partial;
    draft.meta.confidence = if exe {
        Confidence::Exe
    } else {
        Confidence::Data
    };
    let mut sources = Vec::new();
    if info.name.is_some() {
        sources.push("data/gf2/sim_classes.txt".to_owned());
    }
    if info.in_schema {
        sources.push("data/gf2/simgroup_schema.txt".to_owned());
    }
    if info.in_logic || sources.is_empty() {
        sources.push("data/gf2/logic_schema.toml".to_owned());
    }
    let typed = info.attrs.iter().any(|(i, r)| {
        !r.pin
            .as_ref()
            .is_some_and(|p| matches!(p.pin, PinKind::In | PinKind::Out))
            && game_types::attr_type(hash, *i).is_some()
    });
    if typed {
        sources.push("data/gf2/attr_types.toml".to_owned());
        draft.meta.stages.push(TYPES_STAGE);
    }
    sources.append(&mut draft.meta.sources);
    draft.meta.sources = sources;
    draft.meta.tags = vec!["simgroup".to_owned(), "class".to_owned()];
    if let Some(category) = info.category {
        draft.meta.tags.push(category.name().to_owned());
    }
    if info.name.is_none() {
        draft.meta.tags.push("unnamed".to_owned());
    }
    draft
}

fn class_index(all: &BTreeMap<u32, ClassInfo>) -> Draft {
    let mut draft = Draft::new(
        "classes/index.md".to_owned(),
        NoteType::Index,
        "Классы SimGroup".to_owned(),
    );
    let named = all.values().filter(|i| i.name.is_some()).count();
    let objects = all.values().filter(|i| i.category.is_some()).count();
    let mut b = format!(
        "Заметка на каждый класс SimGroup, известный схемам `data/gf2/`: всего {}, с именем {}, \
         без имени {}; классов объектов (со своей категорией в графе логики) — {}. Объектная \
         модель — в заметке [SimGroup, классы, GUID](../engine/simgroup-objects.md).\n\n",
        all.len(),
        named,
        all.len() - named,
        objects,
    );
    b.push_str("| Класс | Хэш | Категория | Атрибутов в схемах |\n|---|---|---|---:|\n");
    let mut rows: Vec<(bool, String, u32)> = all
        .iter()
        .map(|(&h, i)| (i.name.is_none(), class_label(h, i).to_lowercase(), h))
        .collect();
    rows.sort();
    for (_, _, hash) in rows {
        let info = &all[&hash];
        let _ = writeln!(
            b,
            "| [{}]({}.md) | `0x{hash:08x}` | {} | {} |",
            class_label(hash, info),
            class_stem(hash, info),
            info.category.map_or("—", schema::Category::name),
            info.attrs.len(),
        );
    }
    draft.body = b;
    draft.meta.confidence = Confidence::Data;
    draft.meta.sources = vec![
        "data/gf2/sim_classes.txt".to_owned(),
        "data/gf2/simgroup_schema.txt".to_owned(),
        "data/gf2/logic_schema.toml".to_owned(),
    ];
    draft.meta.tags = vec!["index".to_owned(), "simgroup".to_owned()];
    draft
}


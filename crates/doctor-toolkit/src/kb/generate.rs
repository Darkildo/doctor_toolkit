/// The attributes (by packet class) that hold values of the list.
fn enum_users(key: &str, all: &BTreeMap<u32, ClassInfo>) -> Vec<String> {
    let mut out = Vec::new();
    for (class, index, t) in game_types::attr_types() {
        if !matches!(t.ty, SemanticType::Enum(k) if k == key) {
            continue;
        }
        let name = match all.get(class) {
            Some(info) => format!(
                "[{}](../classes/{}.md)",
                class_label(*class, info),
                class_stem(*class, info)
            ),
            None => format!("`0x{class:08x}`"),
        };
        out.push((
            all.get(class)
                .map_or_else(String::new, |i| class_label(*class, i).to_lowercase()),
            *index,
            format!(
                "{name} {index} ({}, подходит {} из {} значений)",
                conf_name(t.conf),
                t.seen.0,
                t.seen.1
            ),
        ));
    }
    out.sort();
    out.into_iter().map(|r| r.2).collect()
}

fn enum_note(e: &EnumDef, all: &BTreeMap<u32, ClassInfo>) -> Draft {
    let mut draft = Draft::new(
        format!("enums/{}.md", e.key),
        NoteType::Enum,
        format!("Перечисление `{}`: {}", e.key, e.ru.to_lowercase()),
    );
    let stored = match e.kind {
        EnumKind::Hash => "хэш `sdbm(lower(имя))`, 32 бита",
        EnumKind::Name => "имя текстом",
        EnumKind::Int => "число",
        EnumKind::Bits => "битовая маска (в поле может быть несколько значений)",
    };
    let named = e.values.iter().filter(|v| v.name.is_some()).count();
    let mut b = format!(
        "- Значений: {} (с именем — {named}).\n- Как хранится в атрибуте: {stored}.\n\
         - Источник: {}.\n- Уверенность: `{}`.\n",
        e.values.len(),
        cell(e.source_ru),
        conf_name(e.conf),
    );
    if named == e.values.len() {
        let ty: String = e
            .key
            .split('_')
            .map(|w| {
                let mut c = w.chars();
                c.next()
                    .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                    .unwrap_or_default()
            })
            .collect();
        let _ = writeln!(
            b,
            "- В коде: Rust `doctor_toolkit::game_types::{ty}`, Python `doctor_toolkit.gf2_types.{ty}`, JSON Schema `#/$defs/{}`.",
            e.key
        );
    } else {
        let _ = writeln!(
            b,
            "- В коде: список `doctor_toolkit::game_types::enum_def(\"{}\")`, Python `doctor_toolkit.gf2_types.{}`, JSON Schema `#/$defs/{}`. Имена значений неизвестны, поэтому типа с вариантами в Rust нет.",
            e.key,
            e.key.to_ascii_uppercase(),
            e.key
        );
    }
    b.push_str("\n## Значения\n\n");
    let has_value = e.values.iter().any(|v| v.value.is_some());
    let has_hash = e.values.iter().any(|v| v.hash.is_some());
    let has_note = e.values.iter().any(|v| !v.note.is_empty());
    let mut head = vec!["Имя"];
    if has_value {
        head.push(if e.kind == EnumKind::Bits {
            "Бит"
        } else {
            "Число"
        });
    }
    if has_hash {
        head.push("Хэш");
    }
    if has_note {
        head.push("Примечание");
    }
    let _ = writeln!(b, "| {} |", head.join(" | "));
    let _ = writeln!(b, "|{}", "---|".repeat(head.len()));
    for v in e.values {
        let mut row = vec![
            v.name
                .map_or_else(|| "—".to_owned(), |n| format!("`{}`", cell(n))),
        ];
        if has_value {
            row.push(match (v.value, e.kind) {
                (Some(x), EnumKind::Bits) => format!("`0x{x:02x}`"),
                (Some(x), _) => x.to_string(),
                (None, _) => "—".to_owned(),
            });
        }
        if has_hash {
            row.push(
                v.hash
                    .map_or_else(|| "—".to_owned(), |h| format!("`0x{h:08x}`")),
            );
        }
        if has_note {
            row.push(cell(v.note));
        }
        let _ = writeln!(b, "| {} |", row.join(" | "));
    }
    let users = enum_users(e.key, all);
    b.push_str("\n## Где встречается\n\n");
    if users.is_empty() {
        b.push_str("Атрибутов SimGroup с этим перечислением в `data/gf2/attr_types.toml` нет.\n");
    } else {
        b.push_str("Атрибуты SimGroup, значения которых — из этого перечисления (`data/gf2/attr_types.toml`):\n\n");
        for u in users {
            let _ = writeln!(b, "- {u}");
        }
    }
    b.push_str("\n## Подробнее\n\n- [Перечисления](index.md)\n- [Сообщения файлов игры](../messages/game-messages.md)\n");
    draft.body = b;
    draft.meta.status = if named == e.values.len() {
        Status::Known
    } else {
        Status::Partial
    };
    draft.meta.confidence = match e.conf {
        schema::Confidence::Exe => Confidence::Exe,
        schema::Confidence::Data => Confidence::Data,
        schema::Confidence::Guess => Confidence::Guess,
    };
    draft.meta.stages = vec![TYPES_STAGE];
    draft.meta.sources = vec![
        "data/gf2/enums.toml".to_owned(),
        "data/gf2/attr_types.toml".to_owned(),
        "research/enum_values.py".to_owned(),
    ];
    draft.meta.tags = vec!["enum".to_owned(), "types".to_owned()];
    draft
}


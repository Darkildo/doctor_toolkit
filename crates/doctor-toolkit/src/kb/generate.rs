/// What a run of the generator did (or, with `check`, would do).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Outcome {
    /// Notes written (new or changed), paths below the knowledge base.
    pub changed: Vec<String>,
    /// Generated notes removed: their class or type is gone from the data.
    pub removed: Vec<String>,
    /// Generated notes in all.
    pub total: usize,
}

impl Outcome {
    pub fn is_clean(&self) -> bool {
        self.changed.is_empty() && self.removed.is_empty()
    }
}

fn apply(kb_dir: &Path, draft: &Draft, today: &str, check: bool, out: &mut Outcome) -> Result<()> {
    let path = kb_dir.join(&draft.rel);
    let existing = match std::fs::read_to_string(&path) {
        Ok(text) => Some(text.replace("\r\n", "\n")),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(io_error(&path, e)),
    };
    out.total += 1;
    let manual = existing
        .as_deref()
        .and_then(manual_section)
        .unwrap_or(MANUAL_DEFAULT);
    if let Some(existing) = &existing {
        let updated = split_front_matter(existing)
            .and_then(|(front, _)| {
                front
                    .lines()
                    .find_map(|l| l.strip_prefix("updated:"))
                    .map(|d| d.trim().to_owned())
            })
            .unwrap_or_default();
        if draft.render(&updated, manual) == *existing {
            return Ok(());
        }
    }
    out.changed.push(draft.rel.clone());
    if !check {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| io_error(parent, e))?;
        }
        std::fs::write(&path, draft.render(today, manual)).map_err(|e| io_error(&path, e))?;
    }
    Ok(())
}

/// Writes the generated notes of the knowledge base in `kb_dir`. With
/// `check` nothing is written: the outcome says what a run would change.
/// `today` (`YYYY-MM-DD`) becomes `updated` of the notes that change.
pub fn run(kb_dir: &Path, inputs: &Inputs, today: &str, check: bool) -> Result<Outcome> {
    let logic = LogicSchema::parse(inputs.logic_schema, inputs.engine_messages)?;
    let tunables = tunables::parse(inputs.tunables)?;
    let all = classes(inputs, &logic)?;
    let mut drafts: Vec<Draft> = all
        .iter()
        .map(|(&hash, info)| class_note(hash, info, &all, &tunables))
        .collect();
    drafts.push(class_index(&all));
    drafts.extend(resource_notes(inputs)?);
    drafts.push(engine_messages(inputs));
    drafts.push(game_messages());
    drafts.extend(game_types::enums().iter().map(|e| enum_note(e, &all)));

    let mut out = Outcome::default();
    for draft in &drafts {
        apply(kb_dir, draft, today, check, &mut out)?;
    }

    // Generated notes of classes and types that are gone from the data.
    let made: HashSet<&str> = drafts.iter().map(|d| d.rel.as_str()).collect();
    let kb = if kb_dir.is_dir() {
        Kb::load(kb_dir)?
    } else {
        Kb::default()
    };
    for note in &kb.notes {
        let generated_folder = note.rel.starts_with("classes/")
            || note.rel.starts_with("resources/")
            // The list of the folder is made below, from the notes.
            || (note.rel.starts_with("enums/") && note.rel != "enums/index.md");
        if generated_folder
            && note.text.contains(GENERATED_MARK)
            && !made.contains(note.rel.as_str())
        {
            out.removed.push(note.rel.clone());
            if !check {
                let path = kb_dir.join(&note.rel);
                std::fs::remove_file(&path).map_err(|e| io_error(&path, e))?;
            }
        }
    }

    // The lists of the folders are made of the notes as they are now.
    let kb = if !check && !out.removed.is_empty() {
        Kb::load(kb_dir)?
    } else {
        kb
    };
    for (folder, title, intro) in FOLDERS {
        let draft = folder_index(&kb, folder, title, intro);
        apply(kb_dir, &draft, today, check, &mut out)?;
    }
    out.changed.sort();
    Ok(out)
}

/// Names of the classes by hash, for tests and tools.
pub fn class_note_names(inputs: &Inputs) -> Result<HashMap<u32, String>> {
    let logic = LogicSchema::parse(inputs.logic_schema, inputs.engine_messages)?;
    Ok(classes(inputs, &logic)?
        .iter()
        .map(|(&hash, info)| (hash, class_stem(hash, info)))
        .collect())
}


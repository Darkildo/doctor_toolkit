    fn gun_hash() -> u32 {
        sdbm(b"gun")
    }

    #[test]
    fn notes_are_made_kept_and_removed() {
        assert_eq!(
            gun_hash(),
            0x332d_5a20,
            "the packet hash of the test schema"
        );
        let dir = tempfile::tempdir().unwrap();
        let kb = dir.path();
        let schema = "332d5a20 6 float 4 damage\n332d5a20 0 string 9\n0000beef 1 int 2\n";
        let first = run(kb, &inputs(schema), "2026-11-16", false).unwrap();
        // Widget, Gun, the packet 8a157691 of the layout, 0000beef; the class
        // list; mesh and the type list; the engine messages and the
        // catalogue of the game's; the value lists; eight folder lists.
        let lists = crate::game_types::enums().len();
        assert_eq!(first.total, 4 + 1 + 2 + 2 + lists + 8);
        assert_eq!(first.changed.len(), first.total);
        let gun = std::fs::read_to_string(kb.join("classes/Gun.md")).unwrap();
        for part in [
            "# Класс `Gun`",
            "категория в графе логики: `object`",
            "[0x8a157691](class-8a157691.md) (1), [0x0000beef](class-0000beef.md) (2)",
            "| 0 | string | вход (сообщение, которое объект слушает) | `fire` | `MsgIn` | роль: exe, имя: guess | 9 |",
            "задержка — атрибут 4",
            "| 6 | float | — | `damage` | — | имя: data | 4 |",
            "| `weapons.pistol.damage` | 6 | float | Pistol: damage \\| one bullet |",
            "confidence: exe",
            "updated: 2026-11-16",
        ] {
            assert!(gun.contains(part), "{part}\n{gun}");
        }
        let beef = std::fs::read_to_string(kb.join("classes/class-0000beef.md")).unwrap();
        assert!(beef.contains("(1): [Gun](Gun.md)"), "{beef}");
        let messages = std::fs::read_to_string(kb.join("messages/engine-messages.md")).unwrap();
        assert!(messages.find("iMsgA").unwrap() < messages.find("iMsgB").unwrap());
        let mesh = std::fs::read_to_string(kb.join("resources/mesh.md")).unwrap();
        assert!(mesh.contains("`0x01961bed`"), "{mesh}");
        assert!(mesh.contains("[docs/formats/geometry.md](../../formats/geometry.md) §2"));
        let list = std::fs::read_to_string(kb.join("messages/index.md")).unwrap();
        assert!(list.contains("[Сообщения движка: полный список](engine-messages.md)"));

        // A second run changes nothing, on another day too.
        let again = run(kb, &inputs(schema), "2027-01-01", false).unwrap();
        assert!(again.is_clean(), "{again:?}");
        assert!(
            run(kb, &inputs(schema), "2027-01-01", true)
                .unwrap()
                .is_clean()
        );

        // A hand-written section survives a change of the data, and only
        // the changed note gets the new date.
        let edited = gun.replace(MANUAL_DEFAULT, "## Заметки\n\nСтреляет.\n");
        assert_ne!(edited, gun);
        std::fs::write(kb.join("classes/Gun.md"), &edited).unwrap();
        assert!(
            run(kb, &inputs(schema), "2027-01-01", true)
                .unwrap()
                .is_clean()
        );
        let schema2 = "332d5a20 6 float 5 damage\n332d5a20 0 string 9\n";
        let check = run(kb, &inputs(schema2), "2027-01-02", true).unwrap();
        assert_eq!(
            check.changed,
            [
                "classes/Gun.md",
                "classes/class-0000beef.md",
                "classes/index.md"
            ]
        );
        let third = run(kb, &inputs(schema2), "2027-01-02", false).unwrap();
        assert_eq!(third.changed, check.changed);
        let gun = std::fs::read_to_string(kb.join("classes/Gun.md")).unwrap();
        assert!(gun.contains("Стреляет.") && !gun.contains("| 4 |"));
        assert!(gun.contains("updated: 2027-01-02"));
        let base = std::fs::read_to_string(kb.join("classes/Widget.md")).unwrap();
        assert!(base.contains("updated: 2026-11-16"));

        // A class that is gone from the data loses its note; a hand-written
        // note of the folder stays.
        std::fs::write(kb.join("classes/Mine.md"), "# By hand\n").unwrap();
        let mut fewer = inputs(schema2);
        fewer.sim_classes = "Gun\n";
        let fourth = run(kb, &fewer, "2027-01-03", false).unwrap();
        assert_eq!(fourth.removed, ["classes/Widget.md"]);
        assert!(!kb.join("classes/Widget.md").exists());
        assert!(kb.join("classes/Mine.md").exists());
    }


/// `Class.3 ×12, Other.0 ×1`; at most `shown` entries.
fn pin_uses_cell(uses: &[game_types::PinUse], shown: usize) -> String {
    if uses.is_empty() {
        return "—".to_owned();
    }
    let mut sorted: Vec<&game_types::PinUse> = uses.iter().collect();
    sorted.sort_by(|a, b| b.count.cmp(&a.count).then(a.class.cmp(b.class)));
    let mut parts: Vec<String> = sorted
        .iter()
        .take(shown)
        .map(|u| format!("`{}.{}` ×{}", u.class, u.index, u.count))
        .collect();
    if sorted.len() > shown {
        parts.push(format!("и ещё {}", sorted.len() - shown));
    }
    parts.join(", ")
}

fn mention_name(label: &str) -> &str {
    match label {
        "lua" => "скрипты Lua",
        "seq" => "ролики",
        "score" => "база очков `score`",
        other => other,
    }
}

fn mentions_cell(mentions: &[(&str, u32)]) -> String {
    if mentions.is_empty() {
        return "—".to_owned();
    }
    mentions
        .iter()
        .map(|(label, n)| format!("{} ({n})", mention_name(label)))
        .collect::<Vec<_>>()
        .join(", ")
}


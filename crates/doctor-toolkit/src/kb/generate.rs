//! `kb-gen`: the generated notes of the knowledge base.
//!
//! From `data/gf2/*` come a note of every SimGroup class (`classes/`), of
//! every resource type (`resources/`), of every value list (`enums/`), the
//! full list of the engine's messages (`messages/engine-messages.md`) and
//! the summary of the messages of the game files
//! (`messages/game-messages.md`); from the notes themselves, the list of
//! every folder (`<folder>/index.md`).
//!
//! A generated note carries [`GENERATED_MARK`] and one hand-written section
//! between [`MANUAL_BEGIN`] and [`MANUAL_END`]: the generator rewrites
//! everything else and keeps that section. A run that changes nothing
//! writes nothing, and `updated` moves only when the text of a note does.
//! The notes are written in Russian, like the documents of `docs/`.


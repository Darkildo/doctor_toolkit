//! Constant tables of the On2 VP6 bitstream (the same values as every VP6
//! decoder: default models, update probabilities, quantizers, trees).

/// A binary tree for the range coder: a node with `val > 0` reads a bit with
/// probability `probs[prob]` and jumps `val` entries ahead on 1 (one entry on 0);
/// a node with `val <= 0` is a leaf for the symbol `-val`.
#[derive(Debug, Clone, Copy)]
pub struct Tree {
    pub val: i8,
    pub prob: u8,
}

const fn n(val: i8, prob: u8) -> Tree {
    Tree { val, prob }
}

const fn leaf(sym: i8) -> Tree {
    Tree { val: -sym, prob: 0 }
}


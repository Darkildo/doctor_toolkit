def message_hash(name):
    """`sdbm(lower(name))`: the message as the game's bus has it."""
    h = 0
    for c in name.encode("latin-1"):
        if 0x41 <= c <= 0x5A:
            c += 0x20
        h = (c + h * 65599) & 0xFFFFFFFF
    return h


def enum_hash(name):
    """What a hash attribute stores for a name of a list (the same hash)."""
    return message_hash(name)

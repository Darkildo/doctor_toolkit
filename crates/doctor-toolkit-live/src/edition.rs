//! Which build the module runs in.
//!
//! The module touches the game only after every check here passes: the PE
//! header of `godfather2.exe` (link time and image size of PC 1.0.789.0,
//! SHA-256 `31f579a8…`, `doctor_toolkit::edition::KNOWN`) and the bytes of
//! each function and instruction it calls, patches or relies on for an
//! address. On another build — or when another mod has patched one of these
//! places — it installs nothing and answers every request with
//! [`crate::ErrorCode::Edition`].
//!
//! The table is generated from the executable
//! (`docs/analysis/live-link.md` §6); a test compares it with the game when
//! `EARS_GF2_DIR` is set.

/// Base of the executable (it has no relocations).
pub const IMAGE_BASE: u32 = 0x0040_0000;
/// `TimeDateStamp` of the PE header (2009-10-05).
pub const TIME_DATE_STAMP: u32 = 0x4AC9_76E5;
/// `SizeOfImage` of the optional header.
pub const SIZE_OF_IMAGE: u32 = 0x00E3_2000;
/// Name of the build for people.
pub const NAME: &str = "PC 1.0.789.0 (build of 2009-10-05)";

/// Bytes expected at one address.
#[derive(Debug, Clone, Copy)]
pub struct Check {
    pub address: u32,
    pub what: &'static str,
    pub bytes: &'static [u8],
}

/// Why the build is not the known one.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Mismatch {
    /// The PE header cannot be read or is not that of the build.
    Header(String),
    /// Bytes differ (another build, or patched by another mod).
    Bytes { address: u32, what: &'static str },
    /// The address cannot be read.
    Unreadable { address: u32, what: &'static str },
}

impl std::fmt::Display for Mismatch {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Header(why) => write!(f, "not {NAME}: {why}"),
            Self::Bytes { address, what } => {
                write!(f, "not {NAME}: other bytes at {address:#010x} ({what})")
            }
            Self::Unreadable { address, what } => {
                write!(f, "not {NAME}: {address:#010x} cannot be read ({what})")
            }
        }
    }
}

/// Checks the build through `read(address, buffer)`, which fills `buffer`
/// with the bytes of the game's image at a virtual address and says
/// whether it could.
pub fn check(read: &mut dyn FnMut(u32, &mut [u8]) -> bool) -> Result<(), Mismatch> {
    check_with(read, CHECKS)
}

/// [`check`] with another table of places: the graphics module
/// ([`crate::render`]) checks its own.
pub fn check_with(
    read: &mut dyn FnMut(u32, &mut [u8]) -> bool,
    checks: &[Check],
) -> Result<(), Mismatch> {
    let mut dos = [0u8; 0x40];
    if !read(IMAGE_BASE, &mut dos) || &dos[0..2] != b"MZ" {
        return Err(Mismatch::Header("no MZ header".into()));
    }
    let pe = u32::from_le_bytes([dos[0x3C], dos[0x3D], dos[0x3E], dos[0x3F]]);
    if pe > 0x1000 {
        return Err(Mismatch::Header("PE header too far".into()));
    }
    let mut head = [0u8; 0x60];
    if !read(IMAGE_BASE + pe, &mut head) || &head[0..4] != b"PE\0\0" {
        return Err(Mismatch::Header("no PE header".into()));
    }
    let u32_at = |i: usize| u32::from_le_bytes([head[i], head[i + 1], head[i + 2], head[i + 3]]);
    let stamp = u32_at(8);
    let size = u32_at(24 + 56);
    if stamp != TIME_DATE_STAMP {
        return Err(Mismatch::Header(format!("link time {stamp:#010x}")));
    }
    if size != SIZE_OF_IMAGE {
        return Err(Mismatch::Header(format!("image size {size:#x}")));
    }
    let mut buf = [0u8; 256];
    for c in checks {
        let got = &mut buf[..c.bytes.len()];
        if !read(c.address, got) {
            return Err(Mismatch::Unreadable {
                address: c.address,
                what: c.what,
            });
        }
        if got != c.bytes {
            return Err(Mismatch::Bytes {
                address: c.address,
                what: c.what,
            });
        }
    }
    Ok(())
}

/// [`check`] on the bytes of an executable file (virtual address = offset in
/// the file + [`IMAGE_BASE`] in every section of this build).
pub fn check_file(data: &[u8]) -> Result<(), Mismatch> {
    check_file_with(data, CHECKS)
}

/// [`check_with`] on the bytes of an executable file.
pub fn check_file_with(data: &[u8], checks: &[Check]) -> Result<(), Mismatch> {
    check_with(
        &mut |va, buf| {
            let Some(at) = va.checked_sub(IMAGE_BASE).map(|o| o as usize) else {
                return false;
            };
            match data.get(at..at + buf.len()) {
                Some(src) => {
                    buf.copy_from_slice(src);
                    true
                }
                None => false,
            }
        },
        checks,
    )
}


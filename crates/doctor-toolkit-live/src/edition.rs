#[cfg(test)]
mod tests {
    use super::*;

    /// An image with the header and every checked byte in place.
    fn fake_image() -> Vec<u8> {
        let mut data = vec![0u8; 0x00A0_0000];
        data[0..2].copy_from_slice(b"MZ");
        data[0x3C..0x40].copy_from_slice(&0x100u32.to_le_bytes());
        data[0x100..0x104].copy_from_slice(b"PE\0\0");
        data[0x108..0x10C].copy_from_slice(&TIME_DATE_STAMP.to_le_bytes());
        data[0x100 + 24 + 56..0x100 + 24 + 60].copy_from_slice(&SIZE_OF_IMAGE.to_le_bytes());
        for c in CHECKS {
            let at = (c.address - IMAGE_BASE) as usize;
            data[at..at + c.bytes.len()].copy_from_slice(c.bytes);
        }
        data
    }

    #[test]
    fn known_image_passes() {
        assert_eq!(check_file(&fake_image()), Ok(()));
    }

    #[test]
    fn other_builds_are_refused() {
        let mut data = fake_image();
        data[0x108] ^= 1;
        assert!(matches!(check_file(&data), Err(Mismatch::Header(_))));

        let mut data = fake_image();
        let c = CHECKS[3];
        data[(c.address - IMAGE_BASE) as usize] ^= 0xFF;
        assert_eq!(
            check_file(&data),
            Err(Mismatch::Bytes {
                address: c.address,
                what: c.what
            })
        );

        // A hook of another mod over the frame call.
        let mut data = fake_image();
        data[(CHECKS[0].address - IMAGE_BASE) as usize] = 0xE9;
        assert!(matches!(check_file(&data), Err(Mismatch::Bytes { .. })));

        let short = &fake_image()[..0x0028_0000];
        assert!(matches!(
            check_file(short),
            Err(Mismatch::Unreadable { .. })
        ));
        assert!(matches!(check_file(b"not a PE"), Err(Mismatch::Header(_))));
    }

    #[test]
    fn checks_fit_and_do_not_overlap() {
        let mut spans: Vec<(u32, u32)> = CHECKS
            .iter()
            .map(|c| (c.address, c.address + c.bytes.len() as u32))
            .collect();
        spans.sort();
        for w in spans.windows(2) {
            assert!(w[0].1 <= w[1].0, "{:#x} overlaps {:#x}", w[0].0, w[1].0);
        }
        assert!(CHECKS.iter().all(|c| c.bytes.len() <= 256));
    }

    /// The table matches the real executable (needs the game).
    #[test]
    fn matches_the_game_when_present() {
        let Some(dir) = std::env::var_os("EARS_GF2_DIR") else {
            return;
        };
        let path = std::path::Path::new(&dir).join("godfather2.exe");
        let Ok(data) = std::fs::read(&path) else {
            return;
        };
        assert_eq!(check_file(&data), Ok(()));
    }
}
